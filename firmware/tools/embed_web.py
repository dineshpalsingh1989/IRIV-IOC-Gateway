"""PlatformIO pre-build step: gzips the dashboard (index.html, app.js, styles.css, install.js from the
repository root) into src/web_files.h, so every firmware build serves the same pages as the website.
Also runs on its own: python firmware/tools/embed_web.py
"""
import gzip
import os

FIRMWARE = os.path.abspath(os.path.join(os.path.dirname(__file__) if "__file__" in globals() else "tools", ".."))
ROOT = os.path.dirname(FIRMWARE)
FILES = [("/", "index.html", "text/html"), ("/app.js", "app.js", "application/javascript"),
         ("/styles.css", "styles.css", "text/css"), ("/install.js", "install.js", "application/javascript")]
OUT = os.path.join(FIRMWARE, "src", "web_files.h")


def build():
    lines = ["// Generated by tools/embed_web.py from the dashboard files. Do not edit.", "#pragma once", "#include <stdint.h>", "#include <stddef.h>", ""]
    table = []
    for i, (path, name, mime) in enumerate(FILES):
        with open(os.path.join(ROOT, name), "rb") as f:
            data = gzip.compress(f.read(), compresslevel=9, mtime=0)  # mtime=0: same input, same bytes
        body = ",".join(str(b) for b in data)
        lines.append(f"static const uint8_t webFile{i}[] = {{{body}}};")
        table.append(f'    {{"{path}", "{mime}", webFile{i}, sizeof(webFile{i})}},')
    lines += ["", "struct WebFile { const char* path; const char* mime; const uint8_t* gz; size_t size; };",
              "static const WebFile webFiles[] = {", *table, "};", ""]
    text = "\n".join(lines)
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if text != old:  # unchanged pages: leave the file alone so nothing recompiles
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)


build()
